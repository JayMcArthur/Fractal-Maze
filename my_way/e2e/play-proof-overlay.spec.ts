import { test, expect } from './fixtures'
import { readFileSync } from 'node:fs'

for (const width of [390, 1440]) {
  test(`proof notebook preserves a live run and its draft at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('play/simple-infinite-hop')
    await page.getByRole('button', { name: 'Move south', exact: true }).click()
    const open = page.getByRole('button', { name: 'Open proof notebook', exact: true })
    await expect(open).toBeEnabled()
    await page.clock.install({ time: new Date('2026-10-20T12:00:00Z') })
    await page.clock.pauseAt(new Date('2026-10-20T12:01:00Z'))
    const marker = page.getByTestId('source-player-marker')
    const point = [await marker.getAttribute('cx'), await marker.getAttribute('cy')]
    const status = await page.locator('.digital-hud').innerText()
    await open.click()
    const dialog = page.getByRole('dialog', { name: 'Proof notebook', exact: true })
    await expect(dialog).toBeVisible()
    await expect(page).toHaveURL(/\/play\/simple-infinite-hop$/)
    await expect(dialog.getByRole('heading', { name: 'Saved claims (0)' })).toBeVisible()
    await dialog.getByLabel('Repeating word', { exact: true }).fill('A')
    await page.clock.runFor(16)
    await page.keyboard.press('ArrowDown')
    expect(await page.locator('.digital-hud').innerText()).toBe(status)
    await expect(marker).toHaveAttribute('cx', point[0]!)
    await expect(marker).toHaveAttribute('cy', point[1]!)
    const box = (await dialog.boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(width)
    expect(box.height).toBeLessThanOrEqual(900)
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(open).toBeFocused()
    expect(await page.locator('.digital-hud').innerText()).toBe(status)
    await open.click()
    await expect(dialog.getByLabel('Repeating word', { exact: true })).toHaveValue('A')
    await dialog.getByRole('button', { name: 'Return to maze', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Undo move', exact: true })).toBeEnabled()
    await expect(page.locator('main a[href*="/workbench/"], main a[href*="/editor/"]')).toHaveCount(0)
  })
}

test('a proof built over Play becomes a live move and survives replay export/import', async ({ page }) => {
  await page.goto('play/simple-infinite-hop')
  await page.getByRole('button', { name: 'Open proof notebook', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Proof notebook', exact: true })
  await dialog.getByLabel('Repeating word', { exact: true }).fill('A')
  const trails = dialog.locator('section.witness')
  await trails.nth(0).getByRole('button', { name: 'enter A → 1', exact: true }).click()
  await trails.nth(1).getByRole('button', { name: 'enter A → 2', exact: true }).click()
  await dialog.getByRole('button', { name: 'Check my proof', exact: true }).click()
  await expect(dialog.locator('.proof-valid')).toBeVisible()
  await dialog.getByRole('button', { name: 'Save checked claim', exact: true }).click()
  await dialog.getByRole('button', { name: 'Return to maze', exact: true }).click()
  await page.getByRole('button', { name: 'Use proof → path 2', exact: true }).click()
  await expect(page.locator('.path-controls [role=status]')).toHaveText('Finish reached.')
  await page.getByRole('button', { name: 'Open proof notebook', exact: true }).click()
  await dialog.locator('.saved-claim > summary').click()
  await expect(dialog.getByRole('button', { name: 'Delete claim', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('button', { name: 'Revise claim', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Return to maze', exact: true }).click()
  await page.getByRole('button', { name: 'Undo move', exact: true }).click()
  await page.getByRole('button', { name: 'Open proof notebook', exact: true }).click()
  await dialog.locator('.saved-claim > summary').click()
  await expect(dialog.getByRole('button', { name: 'Revise claim', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Return to maze', exact: true }).click()
  await page.getByRole('button', { name: 'Use proof → path 2', exact: true }).click()
  await expect(page.locator('.path-controls [role=status]')).toHaveText('Finish reached.')
  await page.getByRole('button', { name: 'Save & play replay', exact: true }).click()
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(page.locator('.replay-proof')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export replay', exact: true }).click()
  const file = (await (await download).path())!
  const recording = JSON.parse(readFileSync(file, 'utf8'))
  expect(recording.maze.definition.claims).toHaveLength(1)
  await page.goto('play/simple-infinite-hop')
  await page.getByLabel('Import replay', { exact: true }).setInputFiles(file)
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(page.locator('.replay-proof')).toBeVisible()
})

test('native block choices and Windischer WIP stay in Play with original credits', async ({ page }) => {
  await page.goto('library')
  await page.getByPlaceholder('Title, author, or tag').fill('Alice')
  const card = page.locator('.library-card').first()
  await expect(card.getByLabel('Maze view')).toHaveCount(0)
  await expect(card.getByRole('link', { name: 'Play', exact: true })).toHaveAttribute('href', /\/play\/alice-in-wonderland$/)
  await card.getByRole('link', { name: 'Play', exact: true }).click()
  await expect(page.locator('main a[href*="/editor/"]')).toHaveCount(0)
  const credits = page.getByRole('region', { name: 'Maze credits' })
  await expect(credits).toContainText('Mike Earnest')
  await expect(credits.getByRole('link', { name: /Original artwork/ })).toHaveAttribute('href', /Alice_and_the_Hedge_Maze/)
  await page.goto('library')
  await page.getByPlaceholder('Title, author, or tag').fill('Windischer')
  await page.getByRole('link', { name: 'View WIP', exact: true }).click()
  await expect(page).toHaveURL(/\/play\/draft-maze-images-martin-windischer-windischer-png$/)
  await expect(page.getByRole('heading', { name: 'Playable maze is WIP', exact: true })).toBeVisible()
  await expect(page.locator('.maze-wip img')).toBeVisible()
  await expect(page.locator('main a[href*="/workbench/"]')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Maze credits' })).toContainText('Martin Windischer')
  await expect(page.getByRole('link', { name: 'Original source ↗', exact: true })).toHaveAttribute('href', 'https://www.mathpuzzle.com/17Dec06.html')
})
