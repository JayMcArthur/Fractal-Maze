test('Noke block movement keeps real position, reversals, depth, undo and saved walking', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('play/1611103791037:0.9096318422296219')
  const marker = page.getByTestId('source-player-marker')
  const originalX = await marker.getAttribute('cx')
  const undo = page.getByRole('button', { name: 'Undo move', exact: true })
  const save = page.getByRole('button', { name: 'Save & play replay', exact: true })
  await page.keyboard.press('ArrowLeft')
  await expect(undo).toBeEnabled()
  await expect(marker).not.toHaveAttribute('cx', originalX!)
  await page.keyboard.press('ArrowRight')
  await expect(save).toBeDisabled()
  await expect(marker).toHaveAttribute('cx', originalX!)
  await page.getByRole('button', { name: 'Enter A → path 4', exact: true }).click()
  await expect(undo).toBeEnabled()
  const depth = page.locator('.digital-hud__metrics > div').filter({ hasText: 'Depth' }).locator('dd')
  await expect(depth).toHaveText('1')
  await expect(page.locator('.digital-hud__position')).toContainText('A')
  await page.screenshot({ path: `${captures}/noke-child-phone.png`, fullPage: true })
  await undo.click()
  await expect(depth).toHaveText('0')
  await expect(marker).toHaveAttribute('cx', originalX!)
  await page.keyboard.press('ArrowLeft')
  await expect(save).toBeEnabled()
  await save.click()
  await expect(page.getByLabel('Replay position')).toHaveAttribute('max', '1')
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  await expect(page.getByLabel('Replay position')).toHaveValue('1')
  await expect(page.locator('.path-replay .format-status')).toHaveText('surface · 1')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export replay', exact: true }).click()
  const file = (await (await download).path())!
  const replay = JSON.parse(readFileSync(file, 'utf8'))
  expect(replay.nativeRoute.type).toBe('pathPushdown')
  expect(replay.nativeRoute.physical.moves).toHaveLength(1)
  expect(replay.nativeRoute.physical.moves[0].kind).toBe('walk')
  expect(replay.metrics.maxDepthReached).toBe(0)
  await page.getByLabel('Import replay', { exact: true }).setInputFiles(file)
  await expect(page.getByLabel('Replay position')).toHaveValue('0')
  await expect(marker).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('archived Tsat solutions use physical playback and retain their original export', async ({ page }) => {
  await page.goto('play/1695993784968:0.6965701909885131?replay=bundled-1695993784968:0.6965701909885131')
  await expect(page.getByTestId('source-player-marker')).toBeVisible()
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  await expect(page.getByLabel('Replay position')).not.toHaveValue('0')
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(page.locator('.path-replay .format-status')).toHaveText('surface · Finish')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export replay', exact: true }).click()
  const replay = JSON.parse(readFileSync((await (await download).path())!, 'utf8'))
  expect(replay.nativeRoute.type).toBe('geometricRecursive')
  expect(replay.maze.definition.type).toBe('geometricRecursive')
  expect(replay.nativeRoute.states.at(-1).won).toBe(true)
  expect(replay.status).toBe('complete')
})

