import { expect, test } from './fixtures'
import { mkdirSync, readFileSync } from 'node:fs'
import type { BundledReplay } from '../src/app/library/bundledReplays'

const wire = (JSON.parse(readFileSync('src/data/manifests/shared-replays.json', 'utf8')) as BundledReplay[])
  .filter(bundle => bundle.mazeId === 'wolf-wire-original')
const captures = 'docs/screenshots/wire-pda'
mkdirSync(captures, { recursive: true })

test('the old wire URL uses shared block/source movement, copy depth, undo and original export', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('play/wolf-wire-original')
  const marker = page.getByTestId('source-player-marker')
  await expect(marker).toBeVisible()
  await expect(page.getByLabel('Display style')).toHaveValue('corridors')
  await expect(page.locator('iframe')).toHaveCount(0)
  await page.getByRole('button', { name: 'Enter A → path 3', exact: true }).click()
  const depth = page.locator('.digital-hud__metrics > div').filter({ hasText: 'Depth' }).locator('dd')
  await expect(depth).toHaveText('1')
  await page.getByLabel('Display style').selectOption('source')
  await expect(marker).toBeVisible()
  await expect(depth).toHaveText('1')
  await page.getByLabel('Display style').selectOption('corridors')
  await page.screenshot({ path: `${captures}/wire-child-phone.png`, fullPage: true })
  await page.getByRole('button', { name: 'Undo move', exact: true }).click()
  await expect(depth).toHaveText('0')
  await expect(page.getByRole('button', { name: 'Save & play replay', exact: true })).toBeDisabled()
  await page.keyboard.press('ArrowUp')
  await expect(page.getByRole('button', { name: 'Undo move', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Save & play replay', exact: true }).click()
  await expect(page.getByLabel('Replay position')).toHaveAttribute('max', '1')
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(marker).toBeVisible()
  await page.getByRole('button', { name: 'Return to play', exact: true }).click()
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download', exact: true }).click()
  const original = JSON.parse(readFileSync((await (await downloading).path())!, 'utf8'))
  expect(original.definition).toEqual({ type: 'legacyWire', asset: 'programs/wolf/index.html' })
  expect(original.metadata.id).toBe('wolf-wire-original')
})

test('all eleven named wire solutions use normal block playback and export/import', async ({ page }) => {
  await page.goto('play/draft-maze-images-mark-j-p-wolf-wolfram-2-jpg')
  const select = page.getByLabel('Maze replay', { exact: true })
  for (const bundle of wire) {
    await expect(select.locator(`option[value="${bundle.id}"]`)).toContainText(bundle.title)
    await select.selectOption(bundle.id)
    await expect(page.getByLabel('Replay position')).toHaveAttribute('max', String(bundle.moves))
    await expect(page.locator('.source-artwork > .block-maze-artwork')).toBeVisible()
    await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
    await expect(page.getByTestId('source-player-marker')).toBeVisible()
    await expect(page.locator('.path-replay .format-status')).toHaveText('surface · 17')
    await expect(page.getByLabel('Replay position')).toHaveValue(String(bundle.moves))
  }
  await page.screenshot({ path: `${captures}/named-solution-desktop.png`, fullPage: true })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export replay', exact: true }).click()
  const file = (await (await download).path())!
  const replay = JSON.parse(readFileSync(file, 'utf8'))
  expect(replay.nativeRoute.type).toBe('pathPushdown')
  expect(replay.playArtwork.blockSize).toBeGreaterThan(0)
  expect(replay.maze.artwork.asset).toContain('Wolfram_2.jpg')
  await page.getByLabel('Import replay', { exact: true }).setInputFiles(file)
  await expect(page.getByLabel('Replay position')).toHaveValue('0')
  await page.getByRole('combobox', { name: 'Speed', exact: true }).selectOption('0.5')
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause replay', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause replay', exact: true }).click()
  const paused = await page.getByLabel('Replay position').inputValue()
  await page.waitForTimeout(200)
  await expect(page.getByLabel('Replay position')).toHaveValue(paused)
})

