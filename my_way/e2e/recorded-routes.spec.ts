import { expect, test } from './fixtures'
import type { Locator } from '@playwright/test'
import { readFileSync } from 'node:fs'

async function descend(board: Locator) {
  await board.getByRole('button', { name: 'Move south', exact: true }).click()
  await board.getByRole('button', { name: 'Move south', exact: true }).click()
  await board.getByRole('button', { name: /^Enter A to path / }).click()
  await expect(board.locator('.witness-maze__position')).toContainText('Depth 1')
}

for (const width of [390, 1440]) {
  test(`record routes, pick starts graphically and follow a named connection at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('play/simple-infinite-hop')
    await page.getByRole('button', { name: 'Open proof notebook', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Proof notebook', exact: true })
    const left = dialog.getByRole('region', { name: 'Left trail', exact: true })
    const right = dialog.getByRole('region', { name: 'Right trail', exact: true })
    await descend(right)
    await left.getByRole('button', { name: 'Choose starting line', exact: true }).click()
    await left.getByRole('button', { name: 'Start on Line 2', exact: true }).click()
    await expect(right.locator('.witness-maze__position')).toContainText('Depth 1')
    await left.getByRole('button', { name: 'Choose starting line', exact: true }).click()
    const start = left.getByRole('button', { name: 'Start on Line 1', exact: true })
    await start.focus()
    await page.keyboard.press('Enter')
    await descend(left)
    await left.getByRole('button', { name: 'Finish recording', exact: true }).click()
    await expect(left.getByRole('status')).toHaveText('Route paused')
    await expect(left.getByRole('button', { name: 'Move south', exact: true })).toHaveCount(0)
    await left.getByRole('button', { name: 'Choose starting line', exact: true }).click()
    await left.getByRole('button', { name: 'Cancel selection', exact: true }).click()
    await expect(left.getByRole('status')).toHaveText('Route paused')
    await left.locator('.witness-maze').focus()
    await page.keyboard.press('ArrowDown')
    await expect(left.locator('.witness-maze__position')).toContainText('Depth 1')
    await left.getByRole('button', { name: 'Resume recording', exact: true }).click()
    await expect(left.getByRole('status')).toHaveText('Recording your route')
    await dialog.getByRole('button', { name: 'Check my proof', exact: true }).click()
    const card = dialog.getByRole('complementary', { name: 'Saved connections', exact: true })
    await expect(card.getByLabel('Shared infinite limit')).toContainText('Repeat A forever')
    await card.getByRole('textbox', { name: 'Connection 1 name', exact: true }).fill('The first descent')
    await dialog.getByRole('button', { name: 'Check my proof', exact: true }).focus()
    await expect(card.getByRole('article')).toHaveAttribute('aria-label', 'The first descent')
    await card.scrollIntoViewIfNeeded()
    await page.screenshot({ path: test.info().outputPath(`saved-connection-${width}.png`) })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await card.getByRole('button', { name: 'Follow → Line 2', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('.path-controls [role=status]')).toHaveText('Finish reached.')
    await page.getByRole('button', { name: 'Save & play replay', exact: true }).click()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Export replay', exact: true }).click()
    const recording = JSON.parse(readFileSync((await (await download).path())!, 'utf8'))
    expect(recording.maze.definition.claims[0].name).toBe('The first descent')
    expect(recording.nativeRoute.proofSteps).toHaveLength(1)
    await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
    await expect(page.locator('.replay-proof')).toBeVisible()
  })
}
