import { expect, test } from './fixtures'
import { readFileSync } from 'node:fs'

test('zooming beyond finite grid limits preserves exact movement, undo and recorded playback', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('play/koteitan-block')
  await expect(page.getByLabel('Recursive block maze at detail 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Move east', exact: true }).click()
  await expect(page.locator('section .format-status')).toContainText('step 1')
  for (let i = 0; i < 24; i++) await page.getByRole('button', { name: 'Zoom deeper', exact: true }).click()
  await expect(page.locator('section .format-status')).toContainText('detail 25')
  await expect(page.locator('section .format-status')).toContainText('step 1')
  await page.getByRole('button', { name: 'Move north', exact: true }).click()
  await expect(page.locator('section .format-status')).toContainText('step 2')
  await page.getByRole('button', { name: 'Move south', exact: true }).click()
  await expect(page.locator('section .format-status')).toContainText('step 1')
  await page.getByRole('button', { name: 'Move north', exact: true }).click()
  await page.getByRole('button', { name: 'Save & play replay', exact: true }).click()
  await expect(page.getByLabel('Replay position')).toHaveAttribute('max', '2')
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(page.getByLabel('Recursive block maze at detail 25', { exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export replay', exact: true }).click()
  const file = (await (await download).path())!
  const replay = JSON.parse(readFileSync(file, 'utf8'))
  expect(replay.nativeRoute.type).toBe('fractalBlock')
  expect(replay.nativeRoute.details).toEqual([1, 25])
  expect(replay.nativeRoute.states.at(-1).y.digits).toHaveLength(25)
  await page.getByLabel('Import replay', { exact: true }).setInputFiles(file)
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(page.getByLabel('Recursive block maze at detail 25', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('an existing finite solution uses the recursive renderer and displays the finish and true depth', async ({ page }) => {
  await page.goto('play/koteitan-block?replay=bundled-koteitan-block')
  await expect(page.getByLabel('Recursive block maze at detail 5', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
  await expect(page.locator('.replay-field .format-status')).toContainText('Finish reached · Depth 0')
  await expect(page.getByLabel('Replay position')).toHaveValue('1756')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export replay', exact: true }).click()
  const replay = JSON.parse(readFileSync((await (await download).path())!, 'utf8'))
  expect(replay.nativeRoute.type).toBe('blockRecursive')
  expect(replay.nativeRoute.depth).toBe(5)
})

for (const [id, detail, moves] of [['koteitan-block-3', 2, 9], ['koteitan-block-5', 5, 3979]] as const) {
  test(`${id} opens playable and shares an exact solution beyond the old missing endpoints`, async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`play/${id}`)
    await expect(page.getByRole('button', { name: 'Find finite route', exact: true })).toBeEnabled()
    for (let i = 1; i < detail; i++) await page.getByRole('button', { name: 'Zoom deeper', exact: true }).click()
    await page.keyboard.press('ArrowUp')
    await expect(page.locator('section .format-status')).toContainText('step 1')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(page.locator('section .format-status')).toContainText('step 0')
    await page.goto(`play/${id}?replay=bundled-${id}`)
    await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
    await expect(page.locator('.replay-field .format-status')).toContainText('Finish reached · Depth 0')
    await expect(page.getByLabel('Replay position')).toHaveValue(String(moves))
    await expect(page.getByLabel(`Recursive block maze at detail ${detail}`, { exact: true })).toBeVisible()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Export replay', exact: true }).click()
    const file = (await (await download).path())!
    const replay = JSON.parse(readFileSync(file, 'utf8'))
    expect(replay.nativeRoute.type).toBe('fractalBlock')
    expect(replay.nativeRoute.details).toEqual(Array(moves).fill(detail))
    await page.getByLabel('Import replay', { exact: true }).setInputFiles(file)
    await expect(page).toHaveURL(new RegExp(`play/${id}\\?replay=(?!bundled-)`))
    await expect(page.getByLabel('Replay position')).toHaveValue('0')
    await page.getByRole('button', { name: 'Seek to end', exact: true }).click()
    await expect(page.locator('.replay-field .format-status')).toContainText('Finish reached · Depth 0')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
